"""Cross-language check: the Python port of the help analyzer and ranking agrees with the TypeScript implementation.

The golden file is generated by ``src/frontend/scripts/help/golden.ts`` from the TypeScript analyzer, indexer (with the
glossary of manual.md 6.9) and searcher (with the page diversification of 6.5). Each case below is parametrized so that it fails on its own.
"""
from __future__ import annotations

import hashlib
import json
from functools import lru_cache
from pathlib import Path

import pytest

from training.assistant import lexical as L
from training.assistant.lexical import Index

ROOT = Path(__file__).resolve().parents[2]
GOLDEN_PATH = ROOT / "src" / "frontend" / "scripts" / "help" / "fixtures" / "lexical.golden.json"
RETRIEVAL_PATH = ROOT / "training" / "assistant" / "retrieval.json"
TOLERANCE = 1e-9

GOLDEN = json.loads(GOLDEN_PATH.read_text(encoding="utf-8"))
RETRIEVAL = json.loads(RETRIEVAL_PATH.read_text(encoding="utf-8"))
ANALYZE_CASES = GOLDEN["analyze"]
RANKING_GROUPS = GOLDEN["ranking"]
RANKING_CASES = [
    pytest.param(group["lang"], idx, id=f"{group['lang']}-{idx:02d}")
    for group in RANKING_GROUPS
    for idx in range(len(group["queries"]))
]


def _ranking_group(lang: str) -> dict:
    return next(g for g in RANKING_GROUPS if g["lang"] == lang)


@lru_cache(maxsize=None)
def _index(lang: str) -> Index:
    group = _ranking_group(lang)
    return Index(group["sections"], lang, group["glossary"])


def _case(lang: str, idx: int) -> dict:
    return _ranking_group(lang)["queries"][idx]


def test_golden_retrieval_matches_python_config():
    assert GOLDEN["retrieval"] == RETRIEVAL
    assert GOLDEN["schema_version"] == 2


@pytest.mark.parametrize("lang", ["en", "it"])
def test_stopword_sha256(lang):
    digest = hashlib.sha256(L.stopwords_path(lang).read_bytes()).hexdigest()
    assert digest == GOLDEN["stopwords_sha256"][lang]


@pytest.mark.parametrize("case", ANALYZE_CASES, ids=[f"{c['lang']}-{i:02d}" for i, c in enumerate(ANALYZE_CASES)])
def test_analyze_tokens(case):
    assert L.tokens(case["text"], case["lang"]) == case["tokens"]


@pytest.mark.parametrize("case", ANALYZE_CASES, ids=[f"{c['lang']}-{i:02d}" for i, c in enumerate(ANALYZE_CASES)])
def test_analyze_stems(case):
    assert L.analyze(case["text"], case["lang"]) == case["stems"]


@pytest.mark.parametrize(("lang", "idx"), RANKING_CASES)
def test_ranking_ids(lang, idx):
    expected = [hit["id"] for hit in _case(lang, idx)["ranked"]]
    actual = [section["id"] for section, _score in _index(lang).rank(_case(lang, idx)["query"], RETRIEVAL)]
    assert actual == expected


@pytest.mark.parametrize(("lang", "idx"), RANKING_CASES)
def test_ranking_scores(lang, idx):
    expected = [hit["score"] for hit in _case(lang, idx)["ranked"]]
    actual = [score for _section, score in _index(lang).rank(_case(lang, idx)["query"], RETRIEVAL)]
    assert len(actual) == len(expected)
    for got, want in zip(actual, expected):
        assert abs(got - want) <= TOLERANCE


def _top_coverage(lang: str, idx: int) -> float:
    """Coverage of the top-ranked section, as the TypeScript ``decide`` computes it (0 when nothing ranks)."""
    index = _index(lang)
    query = _case(lang, idx)["query"]
    hits = index.rank(query, RETRIEVAL)
    if not hits:
        return 0.0
    top_id = hits[0][0]["id"]
    top_index = next(i for i, s in enumerate(index.sections) if s["id"] == top_id)
    return index.coverage(query, top_index)


@pytest.mark.parametrize(("lang", "idx"), RANKING_CASES)
def test_ranking_coverage(lang, idx):
    assert abs(_top_coverage(lang, idx) - _case(lang, idx)["coverage"]) <= TOLERANCE


@pytest.mark.parametrize(("lang", "idx"), RANKING_CASES)
def test_ranking_in_scope(lang, idx):
    params = RETRIEVAL["out_of_scope"]
    query_terms = len(L.analyze(_case(lang, idx)["query"], lang))
    coverage = _top_coverage(lang, idx)
    in_scope = query_terms >= params["min_query_terms"] and coverage >= params["min_coverage"]
    assert in_scope == _case(lang, idx)["in_scope"]
