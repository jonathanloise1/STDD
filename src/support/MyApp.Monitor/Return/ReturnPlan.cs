using System.Globalization;
using System.Text;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using MyApp.Monitor.Pack;
using MyApp.Monitor.Tools;

namespace MyApp.Monitor.Return;

/// <summary>The files of a return (operations.md 15), as text, ready to be written. Nothing here touches git or GitHub.</summary>
public sealed record ReturnPlan(
    string IncidentId, string Outcome, bool NeedsChange, string BranchName, string PullRequestBody, string? RunbookPath, string? RunbookText, JsonObject? SignatureChange,
    IReadOnlyList<string> Notes);

/// <summary>
/// The return loop (operations.md 15, G5): from a closed incident's outcome to the content of the pull request: the branch name, the runbook section as it must
/// read after the change (status, fixed-in release or noise decision, History line), the effect of that on the signature, and the pull request text of
/// <c>fix.agent.md</c>. The repository is only read. A person or the fix agent applies the files; creating the branch, committing, pushing and opening the
/// pull request need the owner's approval (CLAUDE.md) and are not done here.
/// </summary>
public static class ReturnPlanner
{
    private static readonly Regex BranchInvalid = new(@"[^A-Za-z0-9._-]+", RegexOptions.CultureInvariant);

    public sealed record Options(string RepositoryRoot, string? Release, DateOnly Today);

    public static ReturnPlan Plan(JsonObject report, SchemaSubsetValidator schema, Options options)
    {
        if (!schema.IsValid(report, out var errors)) throw new MonitorException("the report does not validate against the incident report schema: " + string.Join("; ", errors.Take(3)));
        var id = MonitorJson.ScalarText(report["id"])!;
        if (report["outcome"] is not JsonObject outcome) throw new MonitorException($"{id} has no outcome: only a closed incident goes back to the repository");
        var value = MonitorJson.ScalarText(outcome["value"])!;
        var notes = new List<string>();
        var signature = (JsonObject)report["signature"]!;
        var kind = MonitorJson.ScalarText(signature["kind"])!;
        var subject = MonitorJson.ScalarText(signature["log_key"]) ?? MonitorJson.ScalarText(signature["template_id"]) ?? MonitorJson.ScalarText(signature["id"]) ?? "unknown";
        var branch = BranchName(id, subject);

        if (value == "duplicate")
            return new ReturnPlan(id, value, false, branch, "", null, null, null, ["The outcome is duplicate: no repository change. The incident links the original."]);

        var closed = DateOnly.TryParse((MonitorJson.ScalarText(outcome["closed_at"]) ?? "")[..Math.Min(10, (MonitorJson.ScalarText(outcome["closed_at"]) ?? "").Length)], CultureInfo.InvariantCulture, out var d) ? d : options.Today;
        var reference = MonitorJson.ScalarText(outcome["pull_request"]) ?? MonitorJson.ScalarText(outcome["ticket"]);
        var historyLine = $"- {closed:yyyy-MM-dd} {id} {value}{(reference is null ? "" : " " + reference)}";

        string? runbookPath = null, runbookText = null;
        JsonObject? change = null;
        var anchor = MonitorJson.ScalarText(report["runbook"]?["anchor"]);
        if (kind == "keyed" && anchor is not null) runbookPath = MonitorJson.ScalarText(report["runbook"]!["path"]);
        else if (kind == "template") { runbookPath = "docs/support/unkeyed-runbooks.md"; anchor = MonitorJson.ScalarText(signature["template_id"]); }

        if (runbookPath is not null && anchor is not null)
        {
            var file = Path.Combine(options.RepositoryRoot, runbookPath.Replace('/', Path.DirectorySeparatorChar));
            var section = File.Exists(file) ? FindSection(File.ReadAllText(file), anchor) : null;
            if (section is null) notes.Add($"The runbook section '{anchor}' was not found in {runbookPath}: write it by hand from the template of operations.md 5.4.");
            else (runbookText, change) = Apply(section, value, historyLine, outcome, options, notes);
        }
        else if (value == "unknown_resolved" || kind == "none")
        {
            runbookPath = "docs/areas/{area}/operations.md";
            runbookText = Skeleton(report, value, historyLine, notes);
            change = new JsonObject { ["signature"] = null, ["note"] = "The signature does not exist yet: it is generated by pack build once the test case, the log definition and the runbook below exist." };
        }
        else notes.Add("The report names no runbook: add one (operations.md 5.4) or hand over to development.");

        var body = PullRequestBody(report, outcome, value, kind, subject, runbookPath, change != null, options);
        return new ReturnPlan(id, value, true, branch, body, runbookPath, runbookText, change, notes);
    }

    /// <summary><c>fix/{incident id}-{log key or template id}</c> with only characters git accepts.</summary>
    public static string BranchName(string incidentId, string subject)
    {
        var name = BranchInvalid.Replace($"{incidentId}-{subject}", "-").Trim('-', '.');
        while (name.Contains("..", StringComparison.Ordinal)) name = name.Replace("..", ".", StringComparison.Ordinal);
        if (name.EndsWith(".lock", StringComparison.Ordinal)) name = name[..^5];
        return "fix/" + (name.Length > 100 ? name[..100].TrimEnd('-', '.') : name);
    }

    private static string? FindSection(string markdown, string anchor)
    {
        var lines = markdown.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n');
        var start = Array.FindIndex(lines, l => l.TrimEnd() == "## " + anchor);
        if (start < 0) return null;
        var end = Array.FindIndex(lines, start + 1, l => l.StartsWith("## ", StringComparison.Ordinal));
        return string.Join('\n', lines.Skip(start).Take((end < 0 ? lines.Length : end) - start)).TrimEnd() + "\n";
    }

    private static (string Text, JsonObject Change) Apply(string section, string outcomeValue, string historyLine, JsonObject outcome, Options options, List<string> notes)
    {
        var lines = section.Split('\n').ToList();
        string Field(string name) => lines.First(l => l.StartsWith($"| {name} |", StringComparison.Ordinal)).Split('|')[2].Trim();
        void Set(string name, string value)
        {
            var i = lines.FindIndex(l => l.StartsWith($"| {name} |", StringComparison.Ordinal));
            if (i >= 0) lines[i] = $"| {name} | {value} |";
        }
        var before = new JsonObject { ["status"] = Field("Status"), ["fixed_in"] = Field("Fixed in") };
        var after = new JsonObject();
        switch (outcomeValue)
        {
            case "fixed":
                var release = options.Release;
                if (release is null) notes.Add("Give --release {version} or replace '{release}' in 'Fixed in': it is the release that contains the fix.");
                Set("Status", "Fixed"); Set("Fixed in", release ?? "{release}"); Set("Noise rationale", "None"); Set("Noise expires", "None");
                after["status"] = "Fixed"; after["fixed_in"] = release ?? "{release}";
                break;
            case "noise":
                var rationale = Regex.Replace(MonitorJson.ScalarText(outcome["note"]) ?? "", @"\s+", " ").Trim();
                if (rationale.Length == 0) { rationale = "{one sentence: why this is accepted}"; notes.Add("The outcome has no note: write the rationale (one sentence) in 'Noise rationale'."); }
                var expires = options.Today.AddDays(RunbookParser.MaxNoiseDays).ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);
                Set("Status", "Noise"); Set("Fixed in", "None"); Set("Noise rationale", rationale.Replace("|", "/", StringComparison.Ordinal)[..Math.Min(300, rationale.Length)]); Set("Noise expires", expires);
                after["status"] = "Noise"; after["noise"] = new JsonObject { ["rationale"] = rationale, ["expires"] = expires };
                notes.Add($"Noise expires {expires} (at most {RunbookParser.MaxNoiseDays} days after the merge): renew it in a reviewed pull request.");
                break;
            case "reclassified":
                notes.Add("Change the test case Severity and the definition's level together, and update the Meaning and Resolve text of the runbook: they are for a person to write.");
                break;
            case "unknown_resolved":
                notes.Add("This incident had a signature already: check that the new test case, log definition and runbook replace it and that no template runbook is left for the same pattern.");
                break;
            case "wontfix":
                notes.Add("A recurring pattern is proposed as noise instead: close it again with the outcome noise if it comes back.");
                break;
        }
        var h = lines.FindIndex(l => l.Trim() == "### History");
        if (h < 0) throw new MonitorException("the runbook section has no History heading");
        var next = lines.FindIndex(h + 1, l => l.StartsWith("### ", StringComparison.Ordinal));
        var bodyEnd = next < 0 ? lines.Count : next;
        var existing = lines.Skip(h + 1).Take(bodyEnd - h - 1).Where(l => l.Trim().Length > 0 && l.Trim() != "None.").ToList();
        lines.RemoveRange(h + 1, bodyEnd - h - 1);
        lines.InsertRange(h + 1, new[] { "" }.Concat(existing).Append(historyLine).Append(next < 0 ? "" : ""));
        var text = string.Join('\n', lines).TrimEnd() + "\n";
        var change = new JsonObject { ["before"] = before, ["after"] = after, ["history_added"] = historyLine };
        return (text, change);
    }

    private static string Skeleton(JsonObject report, string value, string historyLine, List<string> notes)
    {
        notes.Add("The log key is chosen when the test case is written ({area}.{action}.{outcome}, development.md 3.1): replace the placeholders, then run pack build.");
        var evidence = (report["investigation"] as JsonObject)?["cause_category"] ?? report["rule_verdict"]?["cause_category"];
        var category = MonitorJson.ScalarText(evidence) ?? "unknown";
        var sb = new StringBuilder();
        sb.Append("## {runbook anchor}\n\n| Field | Value |\n|-------|-------|\n| Log key | `{log key}` |\n| Test case | [{TEST-CASE-ID}](test-cases/{TEST-CASE-ID}.md) |\n");
        sb.Append("| Expected rate | {n} per hour |\n| Fingerprint by | {Property names, or None} |\n");
        sb.Append($"| Cause category | {category} |\n| Status | Active |\n| Fixed in | None |\n| Noise rationale | None |\n| Noise expires | None |\n\n");
        sb.Append("### Meaning\n\n{One to three sentences, in support terms: what happened and who is affected.}\n\n### Check\n\n1. {What to look at, in order.}\n\n");
        sb.Append("### Rule checks\n\nNone.\n\n### Resolve\n\n1. {What support does, or \"Hand over to development\" with the reason.}\n\n### History\n\n");
        sb.Append(historyLine).Append('\n');
        return sb.ToString();
    }

    private static string PullRequestBody(JsonObject report, JsonObject outcome, string value, string kind, string subject, string? runbookPath, bool hasRunbookChange, Options options)
    {
        string T(string name, JsonNode? n) => MonitorJson.ScalarText(n) ?? "none";
        var evidence = ((report["evidence"] as JsonArray) ?? []).Select(e => $"{T("id", e?["id"])}: {T("reference", e?["reference"])}").ToList();
        var files = new List<string>();
        switch (value)
        {
            case "fixed": files.Add("test case (new or corrected) and its test"); files.Add("code"); if (runbookPath is not null) files.Add(runbookPath + " (Status, Fixed in, History)"); break;
            case "unknown_resolved": files.Add("new test case with its Observable trace"); files.Add("log definition (operations.md 3.1)"); files.Add("code"); files.Add("runbook in the area's operations.md"); files.Add("any runbook of the same pattern removed from docs/support/unkeyed-runbooks.md"); break;
            case "noise": if (runbookPath is not null) files.Add(runbookPath + " (Status Noise, rationale, expiry, History)"); break;
            case "reclassified": files.Add("test case Severity and the definition's level (together)"); if (runbookPath is not null) files.Add(runbookPath + " (text and History)"); break;
            case "wontfix": if (runbookPath is not null) files.Add(runbookPath + " (History)"); break;
        }
        var sb = new StringBuilder();
        sb.Append($"Incident: {T("id", report["id"])} ({T("environment", report["environment"])}), outcome {value}\n");
        sb.Append($"Signature: {kind} {subject}\n");
        sb.Append($"Story / test case: {T("story", report["user_story"])} / {T("test case", report["test_case"])}\n");
        sb.Append($"Changes: {string.Join("; ", files)}\n");
        sb.Append($"Evidence: {(evidence.Count == 0 ? "none" : string.Join("; ", evidence))}\n");
        sb.Append($"Reviewer needed: {(value == "noise" ? "yes, a reviewer other than the author (operations.md 5.6)" : "as usual")}\n");
        sb.Append("\n");
        if (MonitorJson.ScalarText(outcome["note"]) is { Length: > 0 } note) sb.Append($"Note from the person who closed it: {note}\n\n");
        if (report["model_verdict"] is JsonObject mv)
            sb.Append($"Model verdict (a model's reading, not a fact): {T("cause", mv["cause"])} ({T("category", mv["cause_category"])}, confidence {T("confidence", mv["confidence"])})\n\n");
        sb.Append("Prepared by `return`: no branch was created, nothing was committed or pushed. Creating the branch, committing, pushing and opening this pull request need the owner's approval.\n");
        return sb.ToString();
    }
}
